def test_skilllift_wildclaw_runner_uses_shared_task_portfolio_state_machine(
    tmp_path: Path,
    monkeypatch,
) -> None:
    wildclaw_root = tmp_path / "WildClawBench"
    write_task(wildclaw_root)
    scores_by_skill: dict[str, float] = {}
    call_index = 0

    monkeypatch.syspath_prepend(str(ROOT / "skilllift"))
    from skilllift.portfolio import RubricHypothesis, SearchDirection, SearchPlan

    class FakePlanner:
        def plan(self, task, parent, previous_plan, history, direction_history, prohibited_novelty_keys):
            rubric = RubricHypothesis("r-workflow", "Improve the public workflow", (task.evidence_ref,))
            directions = tuple(
                SearchDirection(
                    f"d-{index}",
                    "r-workflow",
                    f"Candidate {index} will improve reward",
                    f"capability-{index}",
                    (f"generated-{index}",),
                    None,
                    (task.evidence_ref,),
                    f"generated/{index}",
                )
                for index in range(3)
            )
            return SearchPlan(1, (rubric,), directions)

    class FakeGenerator:
        def generate(self, task, direction, parent):
            name = direction.target_scope[0]
            return f"""diff --git a/{name}/SKILL.md b/{name}/SKILL.md
new file mode 100644
--- /dev/null
+++ b/{name}/SKILL.md
@@ -0,0 +1,8 @@
+---
+name: {name}
+description: Use for the public task.
+triggers: [{name}]
+---
+# {name}
+
+Follow the workflow.
"""

    def fake_task_runner(*, task, model, models_config, thinking, rate_limit_retries, rate_limit_wait_seconds):
        nonlocal call_index
        call_index += 1
        task_payload = json.dumps(task, ensure_ascii=False)
        skill_name = next((name for name in ("generated-2", "generated-1", "generated-0") if name in task_payload), "anchor")
        score = {"anchor": 0.0, "generated-0": 0.25, "generated-1": 0.5, "generated-2": 1.0}[skill_name]
        scores_by_skill[skill_name] = score
        out = tmp_path / "bench-output" / f"{call_index}-{skill_name}"
        out.mkdir(parents=True)
        (out / "agent.log").write_text(f"read /root/skills/{skill_name}/SKILL.md\n", encoding="utf-8")
        return {
            "task_id": task["task_id"],
            "scores": {"overall_score": score},
            "usage": {"total_tokens": 10, "cost_usd": 0.01},
            "error": None,
            "output_dir": str(out),
        }

    runner = SkillLiftWildClawRunner(
        wildclaw_runner=WildClawRunner(task_runner=fake_task_runner),
        planner=FakePlanner(),
        generator=FakeGenerator(),
    )

    result = runner.run(settings(tmp_path, wildclaw_root))

    assert result.summary["source"] == SKILLLIFT_WILDCLAW_SOURCE
    assert result.summary["oracle_runs_count"] == 6
    assert result.summary["oracle_logical_cells"] == 6
    assert result.summary["stop_reason"] == "terminal_candidate"
    assert len(result.records) == 6
    assert set(scores_by_skill.values()) == {0.0, 0.25, 0.5, 1.0}
    assert all(record.task_sample_policy_id == TASK_SAMPLE_POLICY_ID for record in result.records)

    task_state = Path(result.summary["skilllift_exp_dir"]) / "state.json"
    state = json.loads(task_state.read_text(encoding="utf-8"))
    assert len(state["history"]) == 3
    assert set(state["history"][0]) == {
        "candidate_id",
        "direction_id",
        "reward",
        "reward_delta",
        "rank_group",
        "is_valid",
        "is_accepted",
    }
    final_root = Path(result.summary["winner_portfolio_root"])
    assert (final_root / "generated-2" / "SKILL.md").is_file()

    first_record_paths = [record.raw_output_path for record in result.records]
    resumed = runner.run(settings(tmp_path, wildclaw_root))

    assert call_index == 6
    assert [record.raw_output_path for record in resumed.records] == first_record_paths
    assert resumed.resume == {"skipped": 6, "rerun": 0, "run": 0, "failed": 0}


def test_audit_accepts_skilllift_mode_b_single_task_evidence(tmp_path: Path) -> None:
    run_root = tmp_path / "modeb"
    exp_dir = run_root / "skilllift_experiment" / "wildclaw_06_01_mode_b"
    exp_dir.mkdir(parents=True)
    record_paths = []
    for index in range(2):
        task_dir = run_root / "oracle_runs" / "outer_000" / f"s00{index}_v001" / "tasks" / "06_Safety_Alignment_task_1_file_overwrite"
        task_dir.mkdir(parents=True)
        raw = task_dir / "raw_output.json"
        score = task_dir / "score.json"
        manifest = task_dir / "loader" / "loader_manifest.json"
        raw.write_text('{"status":"succeeded"}\n', encoding="utf-8")
        score.write_text('{"score":1.0}\n', encoding="utf-8")
        manifest.parent.mkdir(parents=True)
        manifest.write_text('{"container_skill_dir":"/root/skills"}\n', encoding="utf-8")
        record_paths.append((raw, score, manifest))

    write_json(exp_dir / "oracle_scores" / "outer_000_mode_b_batch.json", {"s000_v001": {"oracle_score": 1.0}})
    write_json(
        exp_dir / "round_states" / "step_000_mode_b.json",
        {
            "mode": "mode_b",
            "rank_alignment": -1.0,
            "verifier_rank": [{"slot": 0, "version": 1}, {"slot": 1, "version": 1}],
            "oracle_rank": [{"slot": 1, "version": 1}, {"slot": 0, "version": 1}],
        },
    )
    prompt_dir = exp_dir / "receipt_revision_attempts" / "receipt_v1_attempt_0"
    prompt_dir.mkdir(parents=True)
    (prompt_dir / "prompt.txt").write_text("rank_alignment verifier_rank oracle_rank rank_mismatches\n", encoding="utf-8")
    write_json(
        run_root / "cell_summary.json",
        {
            "matrix_cell_id": "native_end_to_end__skilllift__wildclawbench__opus-4_7",
            "baseline": "skilllift",
            "benchmark": "wildclawbench",
            "model_label": "opus-4.7",
            "expected_count": 1,
            "succeeded_count": 1,
            "status": "SUCCEEDED",
            "source": SKILLLIFT_WILDCLAW_SOURCE,
            "artifact": str(run_root),
            "skilllift_exp_dir": str(exp_dir),
        },
    )
    write_json(
        run_root / "task_run_records.json",
        [
            {
                "status": "succeeded",
                "task_id": "06_Safety_Alignment_task_1_file_overwrite",
                "task_sample_policy_id": TASK_SAMPLE_POLICY_ID,
                "loader_manifest_path": str(manifest),
                "raw_output_path": str(raw),
                "score_path": str(score),
            }
            for raw, score, manifest in record_paths
        ],
    )

    assert handle_audit(type("Args", (), {"run_root": str(run_root)})()) == 0
    report = json.loads((run_root / "audit_report.json").read_text(encoding="utf-8"))
    assert report["status"] == "passed"

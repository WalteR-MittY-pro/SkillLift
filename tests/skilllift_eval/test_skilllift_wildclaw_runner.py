class FakeFrameworkLLM:
    def __init__(self, *args, **kwargs) -> None:
        self.role = kwargs.get("role", "llm")

    def call_json(self, system_prompt: str, user_prompt: str, temperature: float = 0.0) -> dict:
        if self.role == "skill_generator":
            return {
                "package_mode": "full",
                "files": [
                    {
                        "path": "SKILL.md",
                        "content": (
                            "---\n"
                            "name: skilllift-generated-06-01\n"
                            "description: CoEvo generated guidance for WildClawBench 06-01.\n"
                            "---\n\n"
                            "Read the task carefully and create the required summary without overwriting existing files.\n"
                        ),
                    },
                    {"path": "executor.py", "content": "def main():\n    return None\n"},
                ],
                "entrypoint": "executor.py",
                "metadata": {"summary": "generated by fake framework LLM"},
                "delete_files": [],
            }
        if self.role == "rubricator" and "[Revision Input]" not in user_prompt:
            return _receipt_payload(1)
        if self.role == "rubricator":
            return _receipt_payload(2)
        if self.role == "verifier":
            return {
                "criterion_hits": {"r1": True, "r2": True, "r3": True, "r4": True, "r5": False},
                "rationale": "Verifier ranks both generated packages the same way.",
                "raw_score": 4,
            }
        raise AssertionError(f"unexpected fake LLM role {self.role}")


